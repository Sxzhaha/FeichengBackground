package com.ruoyi.binZhou.sxz.domain;

public class DiseaseKnowledgeAdvice
{
    private Long knowledgeId;
    private String knowledgeName;
    private String introduction;
    private String damageSymptom;
    private String occurrenceRule;
    private String controlMethod;

    public Long getKnowledgeId()
    {
        return knowledgeId;
    }

    public void setKnowledgeId(Long knowledgeId)
    {
        this.knowledgeId = knowledgeId;
    }

    public String getKnowledgeName()
    {
        return knowledgeName;
    }

    public void setKnowledgeName(String knowledgeName)
    {
        this.knowledgeName = knowledgeName;
    }

    public String getIntroduction()
    {
        return introduction;
    }

    public void setIntroduction(String introduction)
    {
        this.introduction = introduction;
    }

    public String getDamageSymptom()
    {
        return damageSymptom;
    }

    public void setDamageSymptom(String damageSymptom)
    {
        this.damageSymptom = damageSymptom;
    }

    public String getOccurrenceRule()
    {
        return occurrenceRule;
    }

    public void setOccurrenceRule(String occurrenceRule)
    {
        this.occurrenceRule = occurrenceRule;
    }

    public String getControlMethod()
    {
        return controlMethod;
    }

    public void setControlMethod(String controlMethod)
    {
        this.controlMethod = controlMethod;
    }
}
